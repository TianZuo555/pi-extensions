// Remove the resume hook that pi-rex 0.4 installed.
//
// Rex now starts pi again in a restored pane by itself. The old hook and its
// records would start pi a second time, or open an old session, so the
// extension removes them. It removes only text that it wrote:
//
// - fish: the `conf.d/rex-resume.fish` file, when it starts with HOOK_MARKER.
// - zsh, bash, and PowerShell: the block between BLOCK_START and BLOCK_END.
// - the records in `<agent dir>/rex-resume`.

import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";

/** First line of the fish hook file that pi-rex 0.4 wrote. */
export const HOOK_MARKER = "# Generated by @tian.zuo/pi-rex.";

/** Start of the block that pi-rex 0.4 added to a shell startup file. */
export const BLOCK_START = "# >>> tian.zuo/pi-rex >>>";

/** End of the block that pi-rex 0.4 added to a shell startup file. */
export const BLOCK_END = "# <<< tian.zuo/pi-rex <<<";

/** Folder below the pi agent directory that held one record per Rex pane. */
export const RESUME_DIR = "rex-resume";

export interface CleanupContext {
  readonly agentDir: string;
  readonly env?: NodeJS.ProcessEnv;
  readonly home?: string;
}

/** Remove the marked block, and the blank line that was added before it. */
export function removeBlock(text: string): string {
  const start = text.indexOf(BLOCK_START);
  const end = text.indexOf(BLOCK_END);
  if (start === -1 || end < start) return text;
  let before = text.slice(0, start);
  let after = text.slice(end + BLOCK_END.length);
  if (after.startsWith("\r\n")) after = after.slice(2);
  else if (after.startsWith("\n")) after = after.slice(1);
  if (before.endsWith("\n\n")) before = before.slice(0, -1);
  return before + after;
}

/** Every file where pi-rex 0.4 could write a block. */
export function blockFiles(env: NodeJS.ProcessEnv, home: string): string[] {
  const configHome = env.XDG_CONFIG_HOME?.trim() || path.join(home, ".config");
  return [
    path.join(env.ZDOTDIR?.trim() || home, ".zshrc"),
    path.join(home, ".bash_profile"),
    path.join(home, ".bash_login"),
    path.join(home, ".profile"),
    path.join(configHome, "powershell", "profile.ps1"),
    path.join(home, "Documents", "PowerShell", "profile.ps1"),
    path.join(home, "Documents", "WindowsPowerShell", "profile.ps1"),
  ];
}

/** The fish file that pi-rex 0.4 wrote. */
export function fishFile(env: NodeJS.ProcessEnv, home: string): string {
  const configHome = env.XDG_CONFIG_HOME?.trim() || path.join(home, ".config");
  return path.join(configHome, "fish", "conf.d", "rex-resume.fish");
}

/**
 * Remove the old hook and records. Returns the hook files that changed. A
 * file that cannot be read or written stays as it is.
 */
export function removeLegacyResume(context: CleanupContext): string[] {
  const env = context.env ?? process.env;
  const home = context.home ?? os.homedir();
  const changed: string[] = [];

  const fish = fishFile(env, home);
  try {
    if (existsSync(fish) && readFileSync(fish, "utf8").startsWith(HOOK_MARKER)) {
      rmSync(fish, { force: true });
      changed.push(fish);
    }
  } catch {
    // Keep the file.
  }

  for (const file of blockFiles(env, home)) {
    try {
      if (!existsSync(file)) continue;
      const current = readFileSync(file, "utf8");
      const next = removeBlock(current);
      if (next === current) continue;
      writeFileSync(file, next);
      changed.push(file);
    } catch {
      // Keep the file.
    }
  }

  try {
    rmSync(path.join(context.agentDir, RESUME_DIR), { recursive: true, force: true });
  } catch {
    // The records do nothing without the hook.
  }
  return changed;
}
