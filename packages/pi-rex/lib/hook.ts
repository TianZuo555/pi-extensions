// Install the shell hook that resumes pi in its Rex pane.
//
// pi cannot start itself after a Rex restart: Rex starts a new shell in each
// restored pane, so the pi process that ran there is gone. The shell reads the
// record that `lib/resume.ts` writes, and starts `pi --session <file>`.
//
// The user should not write that hook by hand. On the first pi session inside a
// Rex pane, this module writes the hook for the pane's shell:
//
// - fish: a drop-in file below `conf.d`.
// - zsh and bash: a marked block at the end of the shell's startup file.
//
// A file that this extension wrote starts with HOOK_MARKER or holds a marked
// block. Everything else belongs to the user and stays unchanged.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";

/** First line of a fish hook file that this extension wrote. */
export const HOOK_MARKER =
  "# Generated by @tian.zuo/pi-rex. Edit or delete this file to stop the hook.";

/** Start of the block this extension appends to a shell startup file. */
export const BLOCK_START = "# >>> tian.zuo/pi-rex >>>";

/** End of the block this extension appends to a shell startup file. */
export const BLOCK_END = "# <<< tian.zuo/pi-rex <<<";

/** Shells that get a hook. */
export type Shell = "fish" | "zsh" | "bash" | "powershell";

const FISH_HOOK = `# Start pi again after the Rex server restarts this pane.
# The pi-rex extension writes <agent dir>/rex-resume/<block id>.
if status is-interactive; and set -q REX_BLOCK
    function __rex_resume --on-event fish_prompt
        functions -e __rex_resume
        set -l agent_dir $HOME/.pi/agent
        # Expand ~ as pi does: fish does not expand it inside a variable.
        set -q PI_CODING_AGENT_DIR; and set agent_dir (string replace -r -- '^~(?=/|$)' $HOME $PI_CODING_AGENT_DIR)
        set -l file $agent_dir/rex-resume/(string replace -- 'block:' '' $REX_BLOCK)
        test -f $file; or return
        set -l record (cat $file)
        test -n "$record[1]"; or return
        cd -- $record[1]; or return
        rm -f $file
        $record[2..]
    end
end
`;

const ZSH_HOOK = `# Start pi again after the Rex server restarts this pane.
if [[ -n \${REX_BLOCK:-} ]]; then
  __rex_dir=\${PI_CODING_AGENT_DIR:-$HOME/.pi/agent}
  [[ $__rex_dir == '~'/* ]] && __rex_dir=$HOME/\${__rex_dir#\\~/}
  __rex_file=$__rex_dir/rex-resume/\${REX_BLOCK#block:}
  if [[ -f $__rex_file ]]; then
    __rex_lines=("\${(@f)$(<$__rex_file)}")
    if [[ -n \${__rex_lines[1]:-} ]] && cd -- \${__rex_lines[1]} 2>/dev/null; then
      __rex_cmd=("\${__rex_lines[@]:1}")
      rm -f $__rex_file
      (( \${#__rex_cmd} )) && "\${__rex_cmd[@]}"
    fi
  fi
  unset __rex_dir __rex_file __rex_lines __rex_cmd
fi`;

const BASH_HOOK = `# Start pi again after the Rex server restarts this pane.
case $- in
  *i*)
    if [ -n "\${REX_BLOCK:-}" ]; then
      __rex_dir="\${PI_CODING_AGENT_DIR:-$HOME/.pi/agent}"
      case "$__rex_dir" in
        "~"/*) __rex_dir="$HOME/\${__rex_dir#\\~/}" ;;
      esac
      __rex_file="$__rex_dir/rex-resume/\${REX_BLOCK#block:}"
      if [ -f "$__rex_file" ]; then
        __rex_lines=()
        while IFS= read -r __rex_line || [ -n "$__rex_line" ]; do
          __rex_lines[\${#__rex_lines[@]}]="$__rex_line"
        done < "$__rex_file"
        if [ -n "\${__rex_lines[0]:-}" ] && cd -- "\${__rex_lines[0]}" 2>/dev/null; then
          rm -f "$__rex_file"
          __rex_cmd=("\${__rex_lines[@]:1}")
          if [ \${#__rex_cmd[@]} -gt 0 ]; then
            "\${__rex_cmd[@]}"
          fi
        fi
      fi
      unset __rex_dir __rex_file __rex_line __rex_lines __rex_cmd
    fi
    ;;
esac`;

const POWERSHELL_HOOK = `# Start pi again after the Rex server restarts this pane.
if ($env:REX_BLOCK) {
  $dir = if ($env:PI_CODING_AGENT_DIR) {
    $env:PI_CODING_AGENT_DIR -replace '^~(?=[\\\\/]|$)', $HOME
  } else {
    Join-Path $HOME '.pi/agent'
  }
  $file = Join-Path (Join-Path $dir 'rex-resume') ($env:REX_BLOCK -replace '^block:', '')
  if (Test-Path -LiteralPath $file) {
    $lines = @(Get-Content -LiteralPath $file)
    if ($lines.Count -ge 2 -and (Test-Path -LiteralPath $lines[0])) {
      $arguments = @()
      if ($lines.Count -gt 2) { $arguments = @($lines[2..($lines.Count - 1)]) }
      Set-Location -LiteralPath $lines[0]
      Remove-Item -LiteralPath $file -Force
      & $lines[1] @arguments
    }
  }
}`;

/** Hook source for each shell, below the marker or between the block markers. */
export const HOOKS: Readonly<Record<Shell, string>> = {
  fish: FISH_HOOK,
  zsh: ZSH_HOOK,
  bash: BASH_HOOK,
  powershell: POWERSHELL_HOOK,
};

/** What happened to the hook file. */
export type HookInstall = {
  readonly path: string;
  readonly status: "created" | "updated" | "kept";
};

/** Where the hook goes, and how this extension recognizes its own text there. */
export type HookTarget = {
  readonly path: string;
  /** `drop-in` owns the whole file; `block` adds a marked block to it. */
  readonly kind: "drop-in" | "block";
};

/** What this module reads from its surroundings. */
export interface HookContext {
  readonly env?: NodeJS.ProcessEnv;
  readonly home?: string;
  readonly platform?: NodeJS.Platform;
}

/** Shell of the pane, from `$SHELL`. Undefined for a shell without a hook. */
export function detectShell(context: HookContext = {}): Shell | undefined {
  const env = context.env ?? process.env;
  // Windows paths use a backslash, which path.basename ignores on POSIX.
  const name = path
    .basename((env.SHELL ?? "").replace(/\\/g, "/"))
    .replace(/\.exe$/i, "")
    .toLowerCase();
  if (name === "fish" || name === "zsh" || name === "bash") return name;
  if (name === "pwsh" || name === "powershell") return "powershell";
  // A Windows pane has no SHELL. PowerShell exports PSModulePath to the
  // programs it starts, and cmd.exe panes keep the one Windows sets.
  if ((context.platform ?? process.platform) === "win32" && env.PSModulePath?.trim())
    return "powershell";
  return undefined;
}

/**
 * Startup file for a bash login shell: the file bash reads first, and
 * `~/.profile` when none exists. A new `~/.bash_profile` would hide the files a
 * user already has, so this never creates one.
 */
function bashStartupFile(home: string): string {
  for (const name of [".bash_profile", ".bash_login", ".profile"]) {
    const file = path.join(home, name);
    if (existsSync(file)) return file;
  }
  return path.join(home, ".profile");
}

/** File that holds the hook for a shell, and how the hook is kept there. */
export function hookTarget(shell: Shell, context: HookContext = {}): HookTarget {
  const env = context.env ?? process.env;
  const home = context.home ?? os.homedir();
  const platform = context.platform ?? process.platform;
  if (shell === "fish") {
    const configHome = env.XDG_CONFIG_HOME?.trim() || path.join(home, ".config");
    return { path: path.join(configHome, "fish", "conf.d", "rex-resume.fish"), kind: "drop-in" };
  }
  if (shell === "zsh") {
    // Zsh reads .zshrc for interactive shells, and ZDOTDIR moves that file.
    const dotdir = env.ZDOTDIR?.trim() || home;
    return { path: path.join(dotdir, ".zshrc"), kind: "block" };
  }
  if (shell === "powershell") {
    // PowerShell reads `$PROFILE.CurrentUserAllHosts`: Documents on Windows,
    // and the config folder on macOS and Linux.
    if (platform === "win32")
      return { path: path.join(home, "Documents", "PowerShell", "profile.ps1"), kind: "block" };
    const configHome = env.XDG_CONFIG_HOME?.trim() || path.join(home, ".config");
    return { path: path.join(configHome, "powershell", "profile.ps1"), kind: "block" };
  }
  return { path: bashStartupFile(home), kind: "block" };
}

/** Add or replace the marked block in a shell startup file. */
export function upsertBlock(current: string, hook: string): string {
  const block = `${BLOCK_START}\n${hook}\n${BLOCK_END}`;
  const start = current.indexOf(BLOCK_START);
  const end = current.indexOf(BLOCK_END);
  if (start !== -1 && end > start) {
    return `${current.slice(0, start)}${block}${current.slice(end + BLOCK_END.length)}`;
  }
  if (current === "") return `${block}\n`;
  const separator = current.endsWith("\n") ? "\n" : "\n\n";
  return `${current}${separator}${block}\n`;
}

/**
 * Write the hook for the pane's shell. `created` and `updated` mean this call
 * changed a file; `kept` means the file already holds the hook, or the user
 * wrote it. Returns undefined for a shell without a hook, and when the write
 * fails.
 */
export function installShellHook(context: HookContext = {}): HookInstall | undefined {
  const shell = detectShell(context);
  if (!shell) return undefined;
  const target = hookTarget(shell, context);
  try {
    const current = existsSync(target.path) ? readFileSync(target.path, "utf8") : undefined;
    // A drop-in file without the marker belongs to the user.
    if (target.kind === "drop-in" && current !== undefined && !current.startsWith(HOOK_MARKER)) {
      return { path: target.path, status: "kept" };
    }
    const next =
      target.kind === "drop-in"
        ? `${HOOK_MARKER}\n${HOOKS[shell]}`
        : upsertBlock(current ?? "", HOOKS[shell]);
    if (current === next) return { path: target.path, status: "kept" };
    mkdirSync(path.dirname(target.path), { recursive: true });
    writeFileSync(target.path, next);
    return { path: target.path, status: current === undefined ? "created" : "updated" };
  } catch {
    // A hook that cannot be written must not break the agent. The records stay,
    // and the user can add the hook by hand.
    return undefined;
  }
}
