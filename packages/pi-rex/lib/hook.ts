// Install the shell hook that resumes pi in its Rex pane.
//
// pi cannot start itself after a Rex restart: Rex starts a new shell in each
// restored pane, so the pi process that ran there is gone. The shell reads the
// record that `lib/resume.ts` writes, and starts `pi --session <file>`.
//
// The user should not write that hook by hand. On the first pi session inside a
// Rex pane, this module writes `~/.config/fish/conf.d/rex-resume.fish` when the
// shell is fish. A file without HOOK_MARKER belongs to the user and stays.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";

/** First line of a hook file that this extension wrote. */
export const HOOK_MARKER =
  "# Generated by @tian.zuo/pi-rex. Edit or delete this file to stop the hook.";

/**
 * Fish hook source below the marker. Fish runs the `fish_prompt` handler once,
 * after the shell reads its configuration. The record holds the folder on line
 * 1 and one argument per line after it.
 */
export const FISH_HOOK = `# Start pi again after the Rex server restarts this pane.
# The pi-rex extension writes <agent dir>/rex-resume/<block id>.
if status is-interactive; and set -q REX_BLOCK
    function __rex_resume --on-event fish_prompt
        functions -e __rex_resume
        set -l agent_dir $HOME/.pi/agent
        # Expand ~ as pi does: fish does not expand it inside a variable.
        set -q PI_CODING_AGENT_DIR; and set agent_dir (string replace -r -- '^~(?=/|$)' $HOME $PI_CODING_AGENT_DIR)
        set -l file $agent_dir/rex-resume/(string replace -- 'block:' '' $REX_BLOCK)
        test -f $file; or return
        set -l record (cat $file)
        test -n "$record[1]"; or return
        cd -- $record[1]; or return
        rm -f $file
        $record[2..]
    end
end
`;

/** What happened to the hook file. */
export type HookInstall = {
  readonly path: string;
  readonly status: "created" | "updated" | "kept";
};

/**
 * Fish hook path for this shell, or undefined when the shell is not fish.
 * Respects `XDG_CONFIG_HOME`, as fish does.
 */
export function fishHookPath(env: NodeJS.ProcessEnv = process.env): string | undefined {
  if (path.basename(env.SHELL ?? "") !== "fish") return undefined;
  const configHome = env.XDG_CONFIG_HOME?.trim() || path.join(os.homedir(), ".config");
  return path.join(configHome, "fish", "conf.d", "rex-resume.fish");
}

/**
 * Write the hook file when the shell is fish. `created` and `updated` mean this
 * call changed the file; `kept` means the file is already right, or the user
 * wrote it. Returns undefined when the shell is not fish or the write fails.
 */
export function installShellHook(env: NodeJS.ProcessEnv = process.env): HookInstall | undefined {
  const file = fishHookPath(env);
  if (!file) return undefined;
  const text = `${HOOK_MARKER}\n${FISH_HOOK}`;
  try {
    const current = existsSync(file) ? readFileSync(file, "utf8") : undefined;
    if (current !== undefined && !current.startsWith(HOOK_MARKER))
      return { path: file, status: "kept" };
    if (current === text) return { path: file, status: "kept" };
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, text);
    return { path: file, status: current === undefined ? "created" : "updated" };
  } catch {
    // A hook that cannot be written must not break the agent. The records stay,
    // and the user can add the hook by hand.
    return undefined;
  }
}
